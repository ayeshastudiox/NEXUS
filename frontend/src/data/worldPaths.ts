export function project(lng: number, lat: number, w: number, h: number): [number, number] {
  const x = ((lng + 180) / 360) * w;
  const y = ((90 - lat) / 180) * h;
  return [x, y];
}

function pts(coords: [number, number][], w: number, h: number): string {
  return coords.map(([lng, lat]) => {
    const [x, y] = project(lng, lat, w, h);
    return `${x.toFixed(1)},${y.toFixed(1)}`;
  }).join(' ');
}

